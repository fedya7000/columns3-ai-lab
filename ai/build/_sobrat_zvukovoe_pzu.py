# -*- coding: utf-8 -*-
"""ПЗУ-ПРОИГРЫВАТЕЛЬ: игра сама, по таймеру, играет звук за звуком.

Зачем. В RetroArch есть настоящий звук, но чтобы записать каждый звук
отдельно, пришлось бы руками ходить по меню SOUND TEST — а его кнопку запуска
наши нажатия не ловят. Вместо меню вешаемся на кадровое прерывание и раз в N
кадров зовём $3D7A с очередным номером. RetroArch тогда просто запускает такое
ПЗУ с --record и --max-frames, без единого нажатия, а резать запись можно по
часам: k-й звук начинается на k*N кадре.

⚠️ Исходное ПЗУ в rom/ НЕ трогаем — патч кладём отдельным файлом в build/.

Заплатка (68000, собрана руками, кладётся в свободные $FF по $07A386):
    movem.l d0-d7/a0-a6,-(a7)     сохранить всё, что может испортить драйвер
    addq.w  #1,(СЧЁТЧИК).l
    cmpi.w  #КАДРОВ,(СЧЁТЧИК).l
    bne     дальше
    clr.w   (СЧЁТЧИК).l
    cmpi.w  #СКОЛЬКО,(НОМЕР).l    дошли до конца списка — больше не играем
    bcc     дальше
    move.w  (НОМЕР).l,d7
    addi.w  #ПЕРВЫЙ,d7
    jsr     $3D7A                 родная постановка звука в очередь
    addq.w  #1,(НОМЕР).l
дальше:
    movem.l (a7)+,d0-d7/a0-a6
    jmp     <прежний обработчик>
"""
import struct
import sys

ИСХОД = 'rom/Columns III (USA).gen'
ВЫХОД = 'build/c3_zvukovoe.gen'
СВОБОДНО = 0x07A386        # 23674 байта $FF — места с запасом
# ⚠️ Первый выбор ($FFD000) оказался ЗАНЯТ: игра держала там свои числа, и
# счётчик заплатки затирался — звук не запускался ни разу. Эти адреса выбраны
# замером (build/_probe_svobodnoe_ozu.py): за 1200 кадров игра в кусок
# $FF0720..$FF8107 не написала ни байта.
СЧЁТЧИК = 0x00FF7F00
НОМЕР = 0x00FF7F02


def дл(v):
    return struct.pack('>I', v & 0xFFFFFFFF)


def сл(v):
    return struct.pack('>H', v & 0xFFFF)


def собрать(кадров, первый, сколько):
    rom = bytearray(open(ИСХОД, 'rb').read())
    прежний = struct.unpack('>I', rom[0x78:0x7C])[0]

    к = bytearray()
    к += b'\x48\xE7\xFF\xFE'                          # 00: movem.l сохранить
    к += b'\x52\x79' + дл(СЧЁТЧИК)                    # 04: addq.w #1,(СЧЁТЧИК)
    к += b'\x0C\x79' + сл(кадров) + дл(СЧЁТЧИК)       # 0A: cmpi.w #кадров
    к += b'\x66\x00' + сл(0x3E - 0x14)                # 12: bne дальше
    к += b'\x42\x79' + дл(СЧЁТЧИК)                    # 16: clr.w (СЧЁТЧИК)
    к += b'\x0C\x79' + сл(сколько) + дл(НОМЕР)        # 1C: cmpi.w #сколько
    к += b'\x64\x00' + сл(0x3E - 0x26)                # 24: bcc дальше
    к += b'\x3E\x39' + дл(НОМЕР)                      # 28: move.w (НОМЕР),d7
    к += b'\x06\x47' + сл(первый)                     # 2E: addi.w #первый,d7
    к += b'\x4E\xB9' + дл(0x3D7A)                     # 32: jsr $3D7A
    к += b'\x52\x79' + дл(НОМЕР)                      # 38: addq.w #1,(НОМЕР)
    assert len(к) == 0x3E, 'смещение уехало: %02X' % len(к)
    к += b'\x4C\xDF\x7F\xFF'                          # 3E: movem.l вернуть
    к += b'\x4E\xF9' + дл(прежний)                    # 42: jmp прежний

    кусок = rom[СВОБОДНО:СВОБОДНО + len(к)]
    assert set(кусок) == {0xFF}, 'место занято, патч не кладу'
    rom[СВОБОДНО:СВОБОДНО + len(к)] = к
    rom[0x78:0x7C] = дл(СВОБОДНО)

    # ⚠️ КОНТРОЛЬНАЯ СУММА. Игра её проверяет: с неверной суммой она молча
    # встаёт, прерывания не включаются, и снаружи это выглядит как «эмулятор
    # работает, а игра не идёт». Час потерян именно на этом.
    s = 0
    for i in range(0x200, len(rom) - 1, 2):
        s = (s + struct.unpack('>H', rom[i:i + 2])[0]) & 0xFFFF
    rom[0x18E:0x190] = struct.pack('>H', s)

    open(ВЫХОД, 'wb').write(bytes(rom))
    return прежний, len(к)


if __name__ == '__main__':
    кадров = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    первый = int(sys.argv[2], 0) if len(sys.argv) > 2 else 1
    сколько = int(sys.argv[3], 0) if len(sys.argv) > 3 else 0xDF
    прежний, n = собрать(кадров, первый, сколько)
    print('собрано: %s' % ВЫХОД)
    print('  заплатка %d байт по $%06X, прежний обработчик $%06X'
          % (n, СВОБОДНО, прежний))
    print('  звук каждые %d кадров (%.1f с), номера с $%02X, всего %d'
          % (кадров, кадров / 60.0, первый, сколько))
    print('  k-й звук начинается на %d*k кадре = %.2f*k секунде'
          % (кадров, кадров / 60.0))
