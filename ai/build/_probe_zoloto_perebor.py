# -*- coding: utf-8 -*-
"""ЗОЛОТО ПЕРЕБОРОМ, а не общим отбором.

Почему так. Золотая фигура приходит ~15 раз за бой против ~200 обычных, и в
общем обучении её три гена почти не чувствуют отбора: за 39 поколений ночью
рекорд не двинулся ни разу после девятого. А чисел всего ТРИ, и решение —
простой максимум из трёх произведений. Значит их можно перебрать прямо.

Считаем ГРУППЫ (цель владельца — длинные бои), одни и те же сиды у всех
правил, оба игрока играют одним и тем же правилом. Разброс по сидам огромный,
поэтому судим по ПАРНОЙ разнице с нынешним правилом, а не по средним.
"""
import os
import sys
from multiprocessing import Pool

sys.path.insert(0, 'tools')
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
import numpy as np
import duel
import train_duel as td

СИДЫ = list(range(5, 236, 8))          # 29 живых сидов
ПРЕДЕЛ = 12000

# (имя, снять свои слои, дать слои врагу, смести цвет)
ПРАВИЛА = [
    ('как сейчас',            0.39, 0.28, 1.21),
    ('только сметать цвет',   0.00, 0.00, 1.00),
    ('только снимать слои',   1.00, 0.00, 0.00),
    ('только дарить слои',    0.00, 1.00, 0.00),
    ('слои важнее (x4)',      1.60, 0.28, 1.21),
    ('слои важнее (x8)',      3.20, 0.28, 1.21),
    ('слои важнее (x16)',     6.40, 0.28, 1.21),
    ('дарить слои активнее',  0.39, 1.50, 1.21),
    ('слои и дарить',         3.20, 1.50, 1.21),
]


def odin(arg):
    номер, jit = arg
    имя, a, b, c = ПРАВИЛА[номер]
    боец, гены, _ = td.load('build/net_duel.json')
    гены = list(гены)
    и = {n: k for k, n in enumerate(duel.GENE_NAMES)}
    гены[и['золото: снять свои слои']] = a
    гены[и['золото: дать слои врагу']] = b
    гены[и['золото: смести цвет']] = c
    r = duel.run_duel(боец, боец, layers=0, max_frames=ПРЕДЕЛ, genes_a=гены,
                      genes_b=гены, quiet=True, jitter=jit)
    g = r.get('групп честных') or [0, 0]
    return (номер, jit, sum(g), 'ошибка' in r)


if __name__ == '__main__':
    задачи = [(н, s) for н in range(len(ПРАВИЛА)) for s in СИДЫ]
    # ядра берём из build/yadra.txt (владелец меняет число на ходу),
    # по умолчанию 10 — чтобы машина оставалась свободной для игры
    try:
        ядер = max(1, int(open('build/yadra.txt').read().strip()))
    except Exception:
        ядер = 10
    print('ядер под перебор: %d' % ядер, flush=True)
    with Pool(ядер) as pool:
        итог = pool.map(odin, задачи)

    по_правилу = {н: {} for н in range(len(ПРАВИЛА))}
    for н, s, g, срыв in итог:
        по_правилу[н][s] = g

    import json
    json.dump({str(н): по_правилу[н] for н in по_правилу},
              open('build/zoloto_syroe.json', 'w'), ensure_ascii=False)
    основа = np.array([по_правилу[0][s] for s in СИДЫ], dtype=float)
    print('%-24s %-9s %-9s %-16s %s'
          % ('правило', 'групп', 'медиана', 'разница с «как сейчас»', 'лучше/хуже сидов'))
    print('-' * 88)
    for н, (имя, a, b, c) in enumerate(ПРАВИЛА):
        v = np.array([по_правилу[н][s] for s in СИДЫ], dtype=float)
        d = v - основа
        ош = d.std(ddof=1) / np.sqrt(len(d)) if len(d) > 1 else 0.0
        вывод = ''
        if н:
            вывод = '%+.1f ± %.1f' % (d.mean(), ош)
            if abs(d.mean()) < 2 * ош:
                вывод += '  (шум)'
            elif d.mean() > 0:
                вывод += '  ЛУЧШЕ'
            else:
                вывод += '  хуже'
        print('%-24s %-9.0f %-9.0f %-16s %d / %d'
              % (имя, v.mean(), np.median(v), вывод,
                 int((d > 0).sum()), int((d < 0).sum())))
