# -*- coding: utf-8 -*-
"""ЗВУК ДЛЯ ЭФИРА — короткие сигналы на события боя.

⚠️ ЭТО НЕ ЗВУК ИГРЫ. Настоящий звук Mega Drive играет драйвер на процессоре
Z80, который сам программирует YM2612; замер 26.08 показал, что за 3000 кадров
68000 захватывает шину Z80 42091 раз и пишет в его память 7172 раза, а в PSG
уходит 4 обращения и в YM2612 ни одного. Чтобы это зазвучало, пришлось бы
эмулировать Z80 целиком плюс шесть FM-каналов — наш эмулятор от такого встанет,
а он нужен быстрым для обучения. Поэтому озвучены СОБЫТИЯ, которые стенд и так
ловит: группа, цепь, пришедший слой, золотая фигура, конец боя.

Всё на стандартной библиотеке: WAV собираем сами (wave + math), играем через
winsound. Ставить ничего не нужно.

⚠️ winsound играет ОДИН звук за раз — новый обрывает предыдущий. Поэтому у
сигналов есть старшинство: цепь не затыкается рядовой группой.
"""
import math
import os
import struct
import sys
import wave

ЧАСТОТА = 22050
ПАПКА = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'build', 'zvuk')

try:
    import winsound
except ImportError:                      # не Windows — молчим, но не падаем
    winsound = None


def _тон(куски, громкость=0.35):
    """Склеивает кусочки (частота, миллисекунды) в один моно-WAV 16 бит.

    Частота 0 — тишина. Края каждого куска приглушаем, иначе на стыках
    получаются щелчки, которые слышно громче самого сигнала.
    """
    данные = bytearray()
    for гц, мс in куски:
        n = int(ЧАСТОТА * мс / 1000.0)
        спад = max(1, n // 8)
        for i in range(n):
            if гц <= 0:
                данные += struct.pack('<h', 0)
                continue
            # квадрат с мягкими краями — по-приставочному, но без щелчков
            фаза = (i * гц / ЧАСТОТА) % 1.0
            волна = 1.0 if фаза < 0.5 else -1.0
            к = min(1.0, i / спад, (n - i) / спад)
            данные += struct.pack('<h', int(32767 * громкость * волна * к))
    return bytes(данные)


# имя -> (куски, громкость, старшинство)
СИГНАЛЫ = {
    'группа':  ([(880, 45)], 0.22, 1),
    'цепь':    ([(700, 50), (900, 50), (1200, 90)], 0.32, 3),
    'слой':    ([(150, 70), (110, 90)], 0.30, 2),
    'золото':  ([(1400, 40), (0, 25), (1400, 40)], 0.28, 2),
    'удар':    ([(300, 60), (220, 80)], 0.30, 2),
    'конец':   ([(600, 90), (450, 90), (300, 160)], 0.35, 4),
    'проба':   ([(660, 70), (990, 110)], 0.30, 5),
}
# имена файлов — ЛАТИНИЦЕЙ: кириллица в пути к WAV лишний риск, а проверить
# его глазами нельзя — winsound молчит об ошибке
ЛАТИНИЦЕЙ = {'группа': 'gruppa', 'цепь': 'cep', 'слой': 'sloy',
             'золото': 'zoloto', 'удар': 'udar', 'конец': 'konec',
             'проба': 'proba'}

_пути = {}
последняя_ошибка = ['']
_играет_до = [0.0]
_старшинство = [0]
# ⛔ ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО (слово владельца 26.08: «какие-то писки, хуй пойми
# что»). Придуманные сигналы не несут смысла игры и мешают смотреть. Включается
# кнопкой в эфире — оставлено как заглушка, пока нет настоящего звука.
включён = [False]


def подготовить():
    """Пишет WAV-файлы, если их ещё нет. Зовётся один раз при запуске."""
    if winsound is None:
        return False
    os.makedirs(ПАПКА, exist_ok=True)
    for имя, (куски, громкость, _) in СИГНАЛЫ.items():
        путь = os.path.abspath(os.path.join(ПАПКА, '%s.wav' % ЛАТИНИЦЕЙ[имя]))
        _пути[имя] = путь
        if os.path.exists(путь):
            continue
        with wave.open(путь, 'wb') as ф:
            ф.setnchannels(1)
            ф.setsampwidth(2)
            ф.setframerate(ЧАСТОТА)
            ф.writeframes(_тон(куски, громкость))
    return True


def играть(имя, сейчас):
    """Сыграть сигнал, если он не глушит что-то более важное.

    `сейчас` — время в секундах (time.perf_counter): звук асинхронный, и без
    учёта длительности рядовые сигналы обрывали бы друг друга на полуслове.
    """
    if not включён[0] or winsound is None or имя not in _пути:
        return
    куски, _, старше = СИГНАЛЫ[имя]
    if сейчас < _играет_до[0] and старше < _старшинство[0]:
        return
    длительность = sum(мс for _, мс in куски) / 1000.0
    _играет_до[0] = сейчас + длительность
    _старшинство[0] = старше
    try:
        winsound.PlaySound(_пути[имя],
                           winsound.SND_FILENAME | winsound.SND_ASYNC
                           | winsound.SND_NODEFAULT)
    except Exception as e:
        # ⚠️ Раньше здесь стояло молчаливое `pass`, и любой сбой звука был
        # невидим — владелец слышал тишину, а причину было не найти.
        последняя_ошибка[0] = repr(e)
        print('звук не сыграл (%s): %s' % (имя, e), file=sys.stderr)


def тишина():
    if winsound is not None:
        try:
            winsound.PlaySound(None, winsound.SND_PURGE)
        except Exception:
            pass


if __name__ == '__main__':
    import time
    if not подготовить():
        print('winsound недоступен — звука не будет')
        sys.exit(1)
    for имя in СИГНАЛЫ:
        print('играю:', имя)
        играть(имя, time.perf_counter())
        time.sleep(0.6)
    print('файлы в', os.path.abspath(ПАПКА))
