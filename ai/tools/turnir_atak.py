# Опыт: когда выгоднее бить? Сети одинаковые, отличается ТОЛЬКО порог атаки.
#
# Мысль владельца, которую и проверяем: кто ударил первым, тот потратил шкалу
# и остался в дефиците, а ответный удар второго приходит уже в профицит.
import os, sys, time
sys.path.insert(0, os.path.dirname(__file__))
import duel, train

head, meta = train.load()
пороги = [10, 20, 30]
seeds = [0, 37, 91]
print('сеть поколения %d, слои 3, лучший из одного раунда' % meta['gen'])
print()
итог = {}
for a in пороги:
    for b in пороги:
        if a >= b:
            continue
        счёт = {'первый': 0, 'второй': 0, 'ничья': 0}
        for s in seeds:
            r = duel.run_duel(head, head, layers=3, max_frames=30000,
                              attack_a=a, attack_b=b, quiet=True, jitter=s)
            w = r.get('победил', 'ничья')
            счёт[w] = счёт.get(w, 0) + 1
            print('   бьёт с %2d против %2d, задержка %2d -> победил %-7s (фигур %s, атак %s)'
                  % (a, b, s, w, r.get('фигур'), r.get('атак')))
        итог[(a, b)] = счёт
        print('порог %2d против %2d: %s' % (a, b, счёт))
        print()
print('=== СВОДКА ===')
for (a, b), c in итог.items():
    print('  бьющий рано (%2d) против копящего (%2d): рано победил %d, копящий %d, ничьих %d'
          % (a, b, c['первый'], c['второй'], c['ничья']))
