# Опыт: рубить по мелочи или копить цепочки ради золота?
#
# Сети берём ОДНУ И ТУ ЖЕ обученную, но подкручиваем ей один вес — тот, что
# отвечает за длину цепочки. Всё остальное совпадает, значит сравнение честное.
#
# Раскладка весов: [скрытый слой 352][смещения 16][выход 16][смещение 1][прямая связка 22]
# В прямой связке признак 16 — собранные камни, 17 — длина цепочки.
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import numpy as np
import brain, duel, simulate, train

head, meta = train.load()
LIN = 352 + 16 + 16 + 1


def variant(mult_chain, mult_stones, name):
    w = np.array(head.w, dtype=np.float64).copy()
    w[LIN + 17] *= mult_chain
    w[LIN + 16] *= mult_stones
    return brain.Net(w), name


копит, имя_к = variant(4.0, 0.4, 'копит цепочки')
мелко, имя_м = variant(0.0, 2.5, 'рубит по мелочи')

print('сначала проверим, что обе версии вообще играют (одиночная укладка):')
for h, n in ((head, 'исходная'), (копит, имя_к), (мелко, имя_м)):
    r = [simulate.play_game(h, 500 + g, 4000, 1)[0] for g in range(3)]
    print('   %-16s фигур: %s' % (n, r))
print()
print('теперь бой, оба бьют при полной шкале (30):')
счёт = {'первый': 0, 'второй': 0, 'ничья': 0}
for s in (0, 37, 91, 150):
    r = duel.run_duel(копит, мелко, layers=3, max_frames=30000,
                      attack_a=30, attack_b=30, quiet=True, jitter=s)
    w = r.get('победил', 'ничья')
    счёт[w] = счёт.get(w, 0) + 1
    print('   задержка %3d -> победил %-7s (фигур %s, атак %s, групп %s)'
          % (s, w, r.get('фигур'), r.get('атак'), r.get('групп')))
print()
print('=== ИТОГ ===  «%s» победил %d раз, «%s» — %d, ничьих %d'
      % (имя_к, счёт['первый'], имя_м, счёт['второй'], счёт['ничья']))
