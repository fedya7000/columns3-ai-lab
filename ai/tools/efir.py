# -*- coding: utf-8 -*-
"""ПРЯМОЙ ЭФИР: смотреть, как ИИ играет, и что у него в голове.

Слева экран приставки, справа — числа боя и решения ботов. Игра идёт
НАСТОЯЩАЯ, ровно та же, что в замерах (duel.run_duel): никаких особых
«показательных» правил, иначе стенд показывал бы не то, что мы меряем.

Запуск:
    python tools\\efir.py          — увеличение 3
    python tools\\efir.py 2        — увеличение 2 (для маленького экрана)

Клавиши:
    ПРОБЕЛ — пауза
    N      — новый бой на другом сиде
    + / -  — быстрее / медленнее (0.25х … без предела)
    ESC    — выход

⚠️ Картинку рисует md.render_np (numpy): прежняя render() тратила 66 мс на
кадр — эфир отставал бы от игры вчетверо. Обе дают ПИКСЕЛЬ В ПИКСЕЛЬ одно
и то же (проверено сравнением кадров).

⚠️ Не путать с tools/stend.py — тот измерительный, гоняет сеть в разных
обвязках и печатает средние.
"""
import os
import sys
import threading
import time
import tkinter as tk

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import ImageTk

import bot_io as io
import duel
import train_duel as td
import zvuk

# Сиды выше 235 до боя не доходят вовсе — известный потолок раздачи.
СИДЫ = [25, 85, 165, 65, 105, 130, 5, 47, 145, 185, 200, 215, 33, 77, 121, 159]
ТЕМПЫ = [0.25, 0.5, 1.0, 2.0, 4.0, 0.0]      # 0.0 = без предела
ФАЗЫ = {'idle': 'думает', 'work': 'ведёт фигуру',
        'attack': 'бьёт', 'drop': 'роняет'}
# ⚠️ Цвета сняты С САМОЙ ИГРЫ (build/_probe_cveta_kamney.py: поле игрока лежит
# на экране с угла (52,4), клетка 16 px, совпало 100 % клеток). Прежние были
# выдуманы мной и почти все не те — слово владельца: «цвета я хз какие».
ЦВЕТА_КАМНЕЙ = {1: '#fc2424', 2: '#00d8fc', 3: '#486cd8',
                4: '#00d890', 5: '#fc9000', 6: '#fcd800'}
ЗОЛОТО = {9: 'снять свои слои', 7: 'дать слои врагу', 8: 'смести цвет'}
ЦВЕТ_ЗОЛОТА = '#e8c060'
ФОН, ТЕКСТ, ТУСКЛО, ЯРКО = '#12141a', '#d8dce6', '#7a8296', '#f0c04a'


class Сорвать(Exception):
    """Просьба бросить текущий бой и начать новый."""


class Эфир:
    def __init__(self, корень, увеличение=3):
        self.увел = увеличение
        self.пауза = False
        self.темп = 2                     # индекс в ТЕМПЫ, то есть 1.0х
        self.новый = False
        self.живой = True
        # ⭐ МИРНЫЙ БОЙ (слово владельца 26.08): боты не бьют и не дарят плиты
        # золотом. Плиты появляются только сами, снять их можно золотой.
        self.мирно = False
        self.сид = 0
        self.мета = {}
        self.кадр_готов = None
        self.данные = {}
        self.события = []
        self.замок = threading.Lock()
        self.часы = 0.0
        self.прошлое = {}
        self.прошлые_группы = [0, 0]
        self.было_золото = [False, False]
        self.звук = zvuk.подготовить()
        self._собрать(корень)
        self.поток = threading.Thread(target=self._играть, daemon=True)
        self.поток.start()
        корень.after(16, self._обновить)

    # ------------------------------------------------------------- окно
    def _собрать(self, корень):
        корень.title('Columns III — ИИ играет')
        корень.configure(bg=ФОН)
        рама = tk.Frame(корень, bg=ФОН)
        рама.pack(fill='both', expand=True)

        self.экран = tk.Label(рама, bg='#000000', bd=0)
        self.экран.grid(row=0, column=0, padx=10, pady=10)

        панель = tk.Frame(рама, bg=ФОН)
        панель.grid(row=0, column=1, sticky='n', padx=(0, 14), pady=10)

        def заголовок(текст):
            tk.Label(панель, text=текст, bg=ФОН, fg=ЯРКО,
                     font=('Consolas', 11, 'bold'), anchor='w'
                     ).pack(fill='x', pady=(10, 2))

        def строка():
            м = tk.Label(панель, text='', bg=ФОН, fg=ТЕКСТ, font=('Consolas', 10),
                         anchor='w', justify='left')
            м.pack(fill='x')
            return м

        заголовок('БОЕЦ')
        self.л_боец = строка()
        заголовок('ПРОГОН')
        self.л_прогон = строка()
        заголовок('СЧЁТ БОЯ')
        self.л_счёт = строка()
        заголовок('ЧТО ДЕЛАЮТ БОТЫ')
        self.л_боты = строка()
        заголовок('СЛЕДУЮЩАЯ ФИГУРА')
        self.холст = tk.Canvas(панель, width=330, height=86, bg=ФОН,
                               highlightthickness=0)
        self.холст.pack(anchor='w')
        заголовок('СОБЫТИЯ')
        self.л_соб = строка()

        # ⚠️ КНОПКИ МЫШЬЮ — главный способ управления. Клавиши по буквам
        # («n») НЕ РАБОТАЮТ при русской раскладке: tkinter отдаёт keysym
        # Cyrillic_te, и привязка к 'n' молча не срабатывает. Слово владельца
        # 25.08: «не работают кнопки». Поэтому ниже разбор по КОДУ клавиши
        # (он от раскладки не зависит), а кнопки есть на любой случай.
        ряд = tk.Frame(рама, bg=ФОН)
        ряд.grid(row=1, column=0, columnspan=2, pady=(0, 10))
        self.кн_режим = None
        for текст, дело in (('⏸ пауза', self._пауза),
                            ('▶ новый бой', self._сменить),
                            ('☮ мирный бой', self._режим),
                            ('🔇 звук: ВЫКЛ', self._звук),
                            ('− медленнее', lambda: self._темп(-1)),
                            ('+ быстрее', lambda: self._темп(+1))):
            кн = tk.Button(ряд, text=текст, command=дело, bg='#232734', fg=ТЕКСТ,
                           activebackground='#333949', activeforeground=ЯРКО,
                           font=('Consolas', 10), relief='flat', bd=0,
                           padx=12, pady=5, highlightthickness=0)
            кн.pack(side='left', padx=4)
            if текст.startswith('☮'):
                self.кн_режим = кн
            if текст.startswith('🔊') or текст.startswith('🔇'):
                self.кн_звук = кн
                if not self.звук:
                    кн.configure(state='disabled', fg=ТУСКЛО)
        self.л_подсказка = tk.Label(ряд, text='   ПРОБЕЛ · N · M · S · +/− · ESC',
                                    bg=ФОН, fg=ТУСКЛО, font=('Consolas', 9))
        self.л_подсказка.pack(side='left')

        # разбор по КОДУ клавиши: 32 пробел, 27 escape, 78 N,
        # 187/107 плюс, 189/109 минус
        def клавиша(e):
            к = e.keycode
            if к == 32:
                self._пауза()
            elif к == 78:
                self._сменить()
            elif к == 77:          # M — мирный бой
                self._режим()
            elif к == 83:          # S — звук
                self._звук()
            elif к in (187, 107):
                self._темп(+1)
            elif к in (189, 109):
                self._темп(-1)
            elif к == 27:
                self._закрыть(корень)
        корень.bind_all('<KeyPress>', клавиша)
        корень.protocol('WM_DELETE_WINDOW', lambda: self._закрыть(корень))
        корень.after(200, корень.focus_force)

    def _пауза(self):
        self.пауза = not self.пауза

    def _сменить(self):
        self.новый = True

    def _режим(self):
        """Переключить мирный бой. Режим задаётся на старте боя, поэтому
        начинаем новый — иначе переключение не подействует."""
        self.мирно = not self.мирно
        if self.кн_режим is not None:
            self.кн_режим.configure(
                text='☮ мирный: ВКЛ' if self.мирно else '☮ мирный бой',
                fg=ЯРКО if self.мирно else ТЕКСТ)
        self.новый = True

    def _звук(self):
        zvuk.включён[0] = not zvuk.включён[0]
        if not zvuk.включён[0]:
            zvuk.тишина()
        self.кн_звук.configure(
            text='🔊 звук: ВКЛ' if zvuk.включён[0] else '🔇 звук: ВЫКЛ',
            fg=ЯРКО if zvuk.включён[0] else ТУСКЛО)
        if zvuk.включён[0]:
            zvuk.играть('проба', time.perf_counter())

    def _темп(self, куда):
        self.темп = max(0, min(len(ТЕМПЫ) - 1, self.темп + куда))

    def _закрыть(self, корень):
        self.живой = False
        корень.after(150, корень.destroy)

    # ------------------------------------------------------------- игра
    def _играть(self):
        н = 0
        while self.живой:
            self.сид = СИДЫ[н % len(СИДЫ)]
            н += 1
            try:
                # чемпиона перечитываем перед КАЖДЫМ боем: если рядом идёт
                # обучение, эфир сам подхватит нового
                боец, гены, мета = td.load('build/net_duel.json')
            except Exception:
                time.sleep(0.5)
                continue
            self.мета = мета or {}
            self.события = []
            self.прошлое = {}
            self._событие('новый бой, сид %d%s'
                          % (self.сид, ', МИРНЫЙ' if self.мирно else ''))
            try:
                duel.run_duel(боец, боец, layers=0, max_frames=600000,
                              genes_a=гены, genes_b=гены, quiet=True,
                              jitter=self.сид, on_frame=self._на_кадре,
                              mnogo_raundov=True, mirno=self.мирно)
                self._событие('бой окончен')
                zvuk.играть('конец', time.perf_counter())
            except Сорвать:
                pass
            except Exception as e:
                self._событие('сбой: %s' % str(e)[:38])
                time.sleep(1.0)

    def _событие(self, текст):
        self.события.append(текст)
        del self.события[:-8]

    def _на_кадре(self, md, f, pilots):
        if not self.живой or self.новый:
            self.новый = False
            raise Сорвать()
        while self.пауза and self.живой and not self.новый:
            time.sleep(0.05)

        множ = ТЕМПЫ[self.темп]
        if множ:
            ждать = self.часы + 1.0 / (60.0 * множ) - time.perf_counter()
            if ждать > 0:
                time.sleep(ждать)
            self.часы = time.perf_counter()

        # картинку снимаем через кадр: глазу хватает тридцати в секунду,
        # а игре достаётся вдвое больше времени на счёт
        if f % 2:
            return
        снимок = self._снять(md, pilots)
        картинка = md.render_np(scale=self.увел)
        with self.замок:
            self.кадр_готов = картинка
            self.данные = снимок

    def _снять(self, md, pilots):
        д = {'кадр': md.frame, 'сид': self.сид,
             'группы': list(getattr(md, '_gruppy', [0, 0])),
             'мета': self.мета, 'игроки': []}
        for i, p in enumerate((io.P1, io.P2)):
            пилот = pilots[i]
            д['игроки'].append({
                'фигур': пилот.placed,
                'атак': пилот.attacks,
                'промахов': пилот.misses,
                'фаза': ФАЗЫ.get(пилот.phase, пилот.phase),
                'столбец': пилот.col if пилот.col is not None else '-',
                'шкала': io.attack_gauge(md, p),
                'слои': io.layers(md, p),
                'порчи': sum(1 for x in io.curses(md, p) if x),
                'верх': io.stack_top(md, p),
                'цепь': io.chain(md, p),
                'следом': io.next_piece(md, p),
            })
        self._поймать_события(д)
        return д

    def _поймать_события(self, д):
        """Короткая лента: то, что глазу трудно поймать в потоке кадров.

        Она же — источник звука: сигналы вешаются ровно на эти события,
        никакого отдельного разбора нет.
        """
        сейчас = time.perf_counter()
        # собранные группы: считаем прирост честного счёта
        for i in (0, 1):
            если_больше = д['группы'][i] - self.прошлые_группы[i]
            if 0 < если_больше <= 9:
                zvuk.играть('группа', сейчас)
            self.прошлые_группы[i] = д['группы'][i]
        # золотая фигура на подходе
        for i in (0, 1):
            золотая = any(v in ЗОЛОТО for v in д['игроки'][i]['следом'])
            if золотая and not self.было_золото[i]:
                zvuk.играть('золото', сейчас)
            self.было_золото[i] = золотая
        for i, имя in enumerate(('ЛЕВЫЙ', 'ПРАВЫЙ')):
            новое = д['игроки'][i]
            старое = self.прошлое.get(i)
            if старое:
                if новое['цепь'] >= 3 and новое['цепь'] > старое['цепь']:
                    self._событие('%s: цепь ×%d' % (имя, новое['цепь']))
                    zvuk.играть('цепь', сейчас)
                if новое['слои'] > старое['слои']:
                    self._событие('%s получил слой (%d)' % (имя, новое['слои']))
                    zvuk.играть('слой', сейчас)
                if новое['порчи'] > старое['порчи']:
                    self._событие('%s: порча' % имя)
                if новое['атак'] > старое['атак']:
                    self._событие('%s ударил' % имя)
                    zvuk.играть('удар', сейчас)
            self.прошлое[i] = новое

    # ------------------------------------------------------------ показ
    def _обновить(self):
        with self.замок:
            картинка = self.кадр_готов
            д = dict(self.данные)
            self.кадр_готов = None
        if картинка is not None:
            self._фото = ImageTk.PhotoImage(картинка)
            self.экран.configure(image=self._фото)
        if д:
            self._написать(д)
        if self.живой:
            self.экран.after(16, self._обновить)

    def _написать(self, д):
        мета = д.get('мета') or {}
        self.л_боец.configure(
            text='поколение %s, счёт %.2f\nобучен на цель: %s\nэтих же весов у обоих игроков'
                 % (мета.get('gen', '?'), мета.get('fitness') or 0.0,
                    'группы' if os.environ.get('OX_CEL') == 'gruppy' else 'победа'))

        множ = ТЕМПЫ[self.темп]
        секунд = д['кадр'] / 60.0
        self.л_прогон.configure(
            text='сид %-4d  кадр %-7d  время %d:%02d\nтемп %s%s'
                 % (д['сид'], д['кадр'], int(секунд // 60), int(секунд % 60),
                    ('%.2fх' % множ) if множ else 'без предела',
                    '    ПАУЗА' if self.пауза else ''))

        л, п = (д['группы'] + [0, 0])[:2]
        а, б = д['игроки']
        self.л_счёт.configure(
            text='                 ЛЕВЫЙ   ПРАВЫЙ\n'
                 'групп собрано    %-7d %-7d\n'
                 'фигур уложено    %-7d %-7d\n'
                 'ударов нанесено  %-7d %-7d\n'
                 'шкала атаки      %-7d %-7d\n'
                 'слоёв получено   %-7d %-7d\n'
                 'порч висит       %-7d %-7d\n'
                 'высота стопки    %-7d %-7d'
                 % (л, п, а['фигур'], б['фигур'], а['атак'], б['атак'],
                    а['шкала'], б['шкала'], а['слои'], б['слои'],
                    а['порчи'], б['порчи'], 19 - а['верх'], 19 - б['верх']))

        self.л_боты.configure(
            text='ЛЕВЫЙ:  %-14s целит в столбец %s\n'
                 'ПРАВЫЙ: %-14s целит в столбец %s\n'
                 'не успели довести фигуру: %d и %d раз'
                 % (а['фаза'], а['столбец'], б['фаза'], б['столбец'],
                    а['промахов'], б['промахов']))

        self._нарисовать_следом(а['следом'], б['следом'])
        self.л_соб.configure(text='\n'.join(self.события[-6:]) or '—')

    def _нарисовать_следом(self, левая, правая):
        """Три камня следующей фигуры, цветами игры.

        Золотая фигура несёт не цвета, а служебные значения 7/8/9 — что она
        сделает, если положить её этим камнем ВНИЗ. Их и подписываем: без
        подписи владелец видел серые квадраты и справедливо не понимал, что это.
        """
        c = self.холст
        c.delete('all')
        for к, (тройка, x0) in enumerate(((левая, 24), (правая, 132))):
            c.create_text(x0 + 14, 8, text=('ЛЕВЫЙ', 'ПРАВЫЙ')[к],
                          fill=ТУСКЛО, font=('Consolas', 8))
            if not any(тройка):
                # между фигурами игра на миг отдаёт нули — не рисуем пустые
                # серые квадраты, иначе кажется, будто показ врёт
                c.create_text(x0 + 14, 40, text='—', fill=ТУСКЛО,
                              font=('Consolas', 12))
                continue
            золотая = any(v in ЗОЛОТО for v in тройка)
            for j, значение in enumerate(тройка):
                цвет = ЦВЕТА_КАМНЕЙ.get(значение)
                if цвет is None and значение in ЗОЛОТО:
                    цвет = ЦВЕТ_ЗОЛОТА
                c.create_rectangle(x0, 16 + j * 16, x0 + 28, 30 + j * 16,
                                   fill=цвет or '#2a2e38', outline='#000000')
                if значение in ЗОЛОТО:
                    c.create_text(x0 + 34, 23 + j * 16, anchor='w',
                                  text=ЗОЛОТО[значение], fill=ЦВЕТ_ЗОЛОТА,
                                  font=('Consolas', 8))
            if золотая:
                c.create_text(x0 + 14, 68, text='ЗОЛОТАЯ', fill=ЦВЕТ_ЗОЛОТА,
                              font=('Consolas', 8, 'bold'))


def main():
    увел = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    корень = tk.Tk()
    Эфир(корень, увел)
    корень.mainloop()


if __name__ == '__main__':
    main()
