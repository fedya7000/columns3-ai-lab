# Глаза и руки бота: чтение состояния игры из ОЗУ и постановка фигуры.
#
# Всё, что здесь используется, описано в docs\IGRA.md (разделы 3, 4, 9, 10).
# Место, где легко ошибиться:
#   +0x60/62/64    — цвета фигуры ПРИ ПОЯВЛЕНИИ, поворот их НЕ меняет;
#   +0x100/120/140 — ЖИВЫЕ цвета падающей фигуры, вот их и крутит кнопка B.
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

ROW = 16               # байт на ряд поля
COLS, ROWS = 6, 13     # видимое поле
HIDDEN = 6             # скрытых рядов над экраном
TOTAL = HIDDEN + ROWS  # 19 рядов в нашем представлении
DEAD_AT = 24           # +0x4C >= 24 — игрок мёртв
BATTLE = 0x20          # значение $FF0406 во время боя

P1, P2 = 0xFF1000, 0xFF1400
# ⚠️ Слотов СЕМЬ, а не пять. Разметка говорила про пять ($FF1000..$FF2000),
# но отрисовка обходит ещё $FF2400 и $FF2800 — а у них все указатели нулевые,
# и они пишут прямо в таблицу векторов ПЗУ по адресу $18. Найдено обходом
# записей в ПЗУ (tools\probe_pzu.py): именно это и обрывало раунд на 35-й
# фигуре, а выглядело как «бот завалился».
SLOTS = [0xFF1000 + 0x400 * i for i in range(7)]
MODE = 0xFF0406

# Свободная память под буферы пустых слотов. Проверено обходом записей:
# кусок $FF8E00..$FFDFFF игра не трогает вообще.
SCRATCH = 0xFF9000
SCRATCH_STEP = 0x1000
SCRATCH_N = 5          # пустых слотов пять: со второго по шестой


# ---------------------------------------------------------------- чтение

def field_base(md, p):
    """Указатель на поле, если он вообще похож на правду.

    После конца раунда игра переинициализирует структуру игрока, и указатель
    какое-то время указывает в никуда — читать по нему нельзя.
    """
    base = md.rl(p + 6)
    if 0xFF0000 <= base - HIDDEN * ROW and base + ROWS * ROW < 0x1000000:
        return base
    return 0


WALL = 9      # то же значение, что и в rules: занято, но в линию не идёт


# Выключатель правки: OX_PRIZRAKI=0 возвращает прежнее поведение (призрак
# читается как пустая клетка) — нужно, чтобы мерить пару на одних сидах.
ПРИЗРАКИ_ВИДИМ = os.environ.get('OX_PRIZRAKI', '1') != '0'


def прозрачно_твёрдая(v):
    """Клетка-ПРИЗРАК: слово не ноль, а цвет (младший байт) ноль.

    Игра держит такую клетку ЗАНЯТОЙ — камни на неё ложатся; рисовать в ней
    нечего — на экране под камнями зияет пустота. Найдено 25.08 по записи
    боя: у ПРАВОГО игрока призраки живут до 6898 кадров и присутствуют на
    поле в 16-73 % партии, у левого их не бывает вовсе (12 сидов, 0 против
    113). Заплатка слотов тут ни при чём — с ней и без неё числа байт в байт.

    ⚠️ Не путать со схлопывающимся камнем: у того флаг $8000 стоит, но ЦВЕТ
    НЕНУЛЕВОЙ, и через миг он исчезнет. У призрака цвет нулевой, и он
    остаётся навсегда.
    """
    return v != 0 and (v & 0xFF) == 0


def field(md, p):
    """Поле сверху вниз: 19 рядов по 6 колонок. Индекс 0 = ряд -6.

    Стена и слои ($00FF) отдаются отдельным значением WALL, а не цветом:
    иначе сплошной ряд слоя выглядит как шесть одинаковых камней и тренажёр
    решает, что он вот-вот схлопнется.
    """
    base = field_base(md, p)
    if not base:
        return [[0] * COLS for _ in range(TOTAL)]
    out = []
    for r in range(-HIDDEN, ROWS):
        row = base + r * ROW
        строка = []
        for c in range(COLS):
            v = md.rw(row + c * 2)
            if (v & 0xFF) == 0xFF or (ПРИЗРАКИ_ВИДИМ and прозрачно_твёрдая(v)):
                строка.append(WALL)     # занято, но в линию не идёт
            else:
                строка.append(v & 0xFF)
        out.append(строка)
    # ⚠️ Слои сдвигают указатель на поле ВНИЗ (docs\IGRA.md, раздел 5в), и
    # нижние строки нашего окна оказываются УЖЕ ПОД ПОЛОМ — там лежит что
    # угодно. Поэтому от первой встреченной стены и ниже всё объявляем стеной.
    for c in range(COLS):
        стена = False
        for r in range(TOTAL):
            if стена:
                out[r][c] = WALL
            elif out[r][c] == WALL:
                стена = True
    return out


def field_raw(md, p):
    """То же поле, но БЕЗ снятия флагов: $8000 = камень помечен к схлопыванию.

    Нужно, чтобы отличать «поле устоялось» от «идёт анимация сбора»: с маской
    помеченный камень неотличим от обычного, и состояние можно прочитать рано.
    """
    base = field_base(md, p)
    if not base:
        return [[0] * COLS for _ in range(TOTAL)]
    out = []
    for r in range(-HIDDEN, ROWS):
        row = base + r * ROW
        out.append([md.rw(row + c * 2) for c in range(COLS)])
    return out


def settled(md, p):
    """Поле окончательное: ничего не помечено к сбору И ничего не падает.

    ⚠️ Одной пометки ($8000) мало. После схлопывания камни сверху падают
    ПОСТЕПЕННО, и игра рисует их в поле на промежуточных местах — в эти кадры
    в столбике зияет дыра, которой через миг не будет. Бот, прочитавший поле в
    такой момент, планирует по картинке, которой не существует.

    Дырка — она же и признак: если под камнем пусто, значит он ещё летит.
    """
    if not field_base(md, p):
        return False
    сырое = field_raw(md, p)
    for row in сырое:
        for v in row:
            # ⚠️ Флаг $8000 при НУЛЕВОМ цвете — это призрак, а не сбор: он
            # никуда не денется. Пока сюда не смотрели, у правого игрока
            # settled() не возвращал True вообще НИ РАЗУ за 66 % партии.
            if (v & 0x8000) and ((v & 0xFF) or not ПРИЗРАКИ_ВИДИМ):
                return False
    for c in range(COLS):
        видел = False
        for r in range(TOTAL):
            v = сырое[r][c]
            if (v & 0xFF) == 0xFF:
                continue                # пол и слои
            if v if ПРИЗРАКИ_ВИДИМ else (v & 0xFF):   # призрак тоже держит камни
                видел = True
            elif видел:
                return False    # под камнем пусто — он ещё падает
    return True


def field_predicted(md, p):
    """Поле таким, каким оно СТАНЕТ через миг.

    ⚠️ Две вещи мешают читать поле как есть, и обе ловились дорого:
      * камни, помеченные к сбору ($8000), ещё лежат в массиве, но исчезнут —
        планировать по ним значит считать поле полнее, чем оно будет;
      * после схлопывания камни падают ПОСТЕПЕННО, и в столбике зияют дыры,
        которых через десяток кадров не будет.
    Ждать некогда — своя фигура в это время летит вниз. Поэтому досчитываем:
    помеченные убираем, остальное роняем гравитацией.
    """
    base = field_base(md, p)
    if not base:
        return [0] * (TOTAL * COLS)
    плоско = []
    for r in range(-HIDDEN, ROWS):
        row = base + r * ROW
        for c in range(COLS):
            v = md.rw(row + c * 2)
            if ПРИЗРАКИ_ВИДИМ and прозрачно_твёрдая(v):
                # призрак никуда не денется: он твёрдый, но безцветный
                плоско.append(WALL)
            elif v & 0x8000:            # схлопывается — считай, его уже нет
                плоско.append(0)
            elif (v & 0xFF) == 0xFF:
                плоско.append(WALL)
            else:
                плоско.append(v & 0xFF)
    # ниже первой стены всё стена (слои сдвигают поле вниз)
    for c in range(COLS):
        стена = False
        for r in range(TOTAL):
            i = r * COLS + c
            if стена:
                плоско[i] = WALL
            elif плоско[i] == WALL:
                стена = True
    return плоско


def live_piece(md, p):
    """Живые цвета падающей фигуры, сверху вниз. Их меняет поворот."""
    return (md.rw(p + 0x100) & 0xFF, md.rw(p + 0x120) & 0xFF, md.rw(p + 0x140) & 0xFF)


def next_piece(md, p):
    """Цвета следующей фигуры, сверху вниз."""
    return (md.rw(p + 0xCE) & 0xFF, md.rw(p + 0xD0) & 0xFF, md.rw(p + 0xD2) & 0xFF)


def piece_col(md, p):
    return md.rw(p + 0x42)


def placed(md, p):
    """Счётчик уложенных фигур — по нему видно, что ход закончился."""
    return md.rw(p + 0x70)


def chain(md, p):
    return md.rw(p + 0x6C)


def groups(md, p):
    return md.rw(p + 0x5C)


def has_special(md, p):
    """Есть ли у игрока в руках особый ($4000) или подлянка ($2000)."""
    for off in (0x100, 0x120, 0x140):
        if md.rw(p + off) & 0x6000:
            return True
    return False


def stack_top(md, p):
    """Индекс верхней занятой клетки (0 = самый верх скрытых рядов, 19 = пусто)."""
    base = field_base(md, p)
    if not base:
        return TOTAL
    for r in range(-HIDDEN, ROWS):
        row = base + r * ROW
        for c in range(COLS):
            v = md.rw(row + c * 2) & 0xFF
            if v and v != 0xFF:
                return r + HIDDEN
    return TOTAL


def curses(md, p):
    """Пять таймеров порчи подряд: +0xF0..+0xF8 (docs\IGRA.md, раздел 5б).

    0 — лево и право поменяны местами
    1 — не работает кнопка поворота
    2 — не видно следующую фигуру
    3 — поле перевёрнуто
    4 — поле чёрно-белое
    """
    return [md.rw(p + 0xF0 + k * 2) for k in range(5)]


def controls_swapped(md, p):
    return md.rw(p + 0xF0) > 0


def rotate_blocked(md, p):
    return md.rw(p + 0xF2) > 0


def attack_gauge(md, p):
    """Шкала атаки (бирюзовое число), потолок 30. Ступень атаки стоит 10."""
    return md.rw(p + 0x5A)


def layers(md, p):
    """Сколько рядов поля отнято: 0 — полное поле, больше — мельче."""
    return md.rw(p + 0x7E)


def dead(md, p):
    """Смерть: игра пишет метку $1000 в поле числа групп (код $006DC0)."""
    return md.rw(p + 0x5C) == 0x1000


def piece_ready(md, p):
    """Цвета фигуры годны только когда все три в диапазоне 1..6.

    Во время схлопывания и при повышении уровня блок +0x100 занят другим:
    игра кладёт туда служебную фигуру-метку (7,8,9) — код $00D344.
    """
    return all(1 <= c <= 6 for c in live_piece(md, p))


def wait_ready(md, p, limit=900):
    """Ждёт, пока игра снова отдаст управляемую фигуру."""
    for _ in range(limit):
        if not in_battle(md) or md.stopped:
            return False
        if piece_ready(md, p) and md.rw(p + 0x76) == 0 and field_base(md, p):
            return True
        md.step_frame()
    return False


def in_battle(md):
    return md.rw(MODE) == BATTLE


def height(fld, c):
    """Сколько рядов занято в колонке, считая от пола вверх."""
    h = 0
    for r in range(TOTAL - 1, -1, -1):
        if fld[r][c] == 0:
            break
        h += 1
    return h


СВАЛКА = 0xFFC000       # общая помойка под писанину мнимых слотов
МНИМЫХ = 16             # докуда закрывать: замер показал разнос до $FF3800


def fix_empty_slots(md):
    """Чинит пре-существующую беду игры: дикая запись из пустого слота.

    В бою заняты два слота из пяти, но отрисовка проходит по ним всем, а
    иногда и УБЕГАЕТ дальше — в свободную память за слотами. У таких мнимых
    слотов все указатели на буферы нулевые, и код $00CE52 пишет по ним сотни
    слов начиная с адреса $18 — прямо в таблицу векторов ПЗУ.

    На приставке запись в картридж пропадает и ничего не происходит. В нашем
    эмуляторе она портила ПЗУ, игра читала испорченную таблицу и улетала в
    мусорный режим. Снаружи это выглядело как «бот завалился на 35-й фигуре»,
    хотя стопка у него была высотой в три камня. Это и держало все бои
    короткими.

    ⚠️ Указателей ЧЕТЫРЕ: +0x0E, +0x16, +0x1C, +0x20. Про +0x0E я узнал
    дороже всего — именно он ведёт в таблицу векторов.

    Лечение: всем мнимым слотам подсунуть указатели в общую свалку. Что они
    туда пишут — не важно, читать это никто не будет.
    """
    for i in range(2, МНИМЫХ):
        slot = 0xFF1000 + 0x400 * i
        md.wl(slot + 0x0E, СВАЛКА)
        md.wl(slot + 0x16, СВАЛКА + 0x400)
        md.wl(slot + 0x1C, СВАЛКА + 0x800)
        md.wl(slot + 0x20, СВАЛКА + 0xC00)


ПРИЗРАК_СРОК = int(os.environ.get('OX_PRIZRAK_SROK', '30'))


def ubrat_prizrakov(md):
    """Гасит ЗАСИДЕВШИЕСЯ клетки-призраки: слово не ноль, а цвет ноль.

    ⭐ СЛОВО ВЛАДЕЛЬЦА 25.08: «камня не должно быть вообще, мы с сестрой очень
    долго играем и такого никогда не было». На приставке такой клетки нет —
    значит её родил НАШ эмулятор, и лечим мы её у себя.

    Что она творила: игра держит клетку ЗАНЯТОЙ (камни ложатся сверху), а
    рисовать в ней нечего — под камнями зияет пустота. Замер по 12 партиям:
    у левого 0 штук, у правого 113, живут до 6898 кадров, на поле в 16-73 %
    партии.

    ⚠️ ГАСИТЬ СРАЗУ НЕЛЬЗЯ — проверено: эмулятор срывается на 3119-м кадре.
    На один-два кадра такое состояние игре нужно по делу (миг схлопывания).
    Поэтому считаем возраст и трогаем только то, что провисело ПРИЗРАК_СРОК
    кадров подряд: настоящий призрак живёт тысячами, рабочее состояние — два.

    Почему лечим здесь, а не в эмуляторе: корень не назван. Три прибора
    подряд соврали, пытаясь поймать запись, — слежка Unicorn пропускает даже
    ЗАВЕДОМО честную запись (подсадная на кадре 220 дала ноль).
    """
    возраст = getattr(md, '_prizrak_vozrast', None)
    if возраст is None:
        возраст = md._prizrak_vozrast = {}
    живые = set()
    for p in (P1, P2):
        base = field_base(md, p)
        if not base:
            continue
        начало = base - HIDDEN * ROW
        блок = bytes(md.uc.mem_read(начало, TOTAL * ROW))
        for r in range(TOTAL):
            строка = r * ROW
            for c in range(COLS):
                i = строка + c * 2
                # старший байт не ноль, младший (цвет) ноль -> призрак
                if блок[i] and not блок[i + 1]:
                    a = начало + i
                    живые.add(a)
                    n = возраст.get(a, 0) + 1
                    возраст[a] = n
                    if n >= ПРИЗРАК_СРОК:
                        md.ww(a, 0)
                        возраст[a] = 0
    for a in list(возраст):
        if a not in живые:
            del возраст[a]


# Простор буферам НАСТОЯЩИХ игроков: у них +0x0E смотрит на $FF0080 и $FF0100,
# то есть по 128 байт на каждого. Цикл отрисовки ($00CE52 → $00CEAE) пишет
# оттуда сотнями слов и УБЕГАЕТ ЗА КРАЙ — прямо в служебные переменные игры.
ПРОСТОР = (0xFF9000, 0xFFB000)      # по 8 КБ на игрока в незанятой памяти


def dat_prostor_igrokam(md):
    """
    Развести буферы настоящих игроков, чтобы отрисовка не топтала служебные
    переменные.

    Как поймали (24.08). `whowrites.py` показал: в $FF0406 (режим игры),
    $FF0418 и $FF0422 пишут соседние инструкции ОДНОГО цикла $00CEBA/$00CEC4/
    $00CECE, все в один кадр, значениями вроде 583 и 26496 — то есть мусором
    от спрайтовой таблицы. Указатель берётся из +0x0E, а у слотов 0 и 1 он
    стоит на $FF0080 и $FF0100, вплотную друг к другу.

    Что это давало: испорченный режим закрывал раунд САМ, без чьей-либо
    смерти. Бои обрывались на 30-50 группах.

    Что стало (сеть, слои 0, сид 47): 7666 кадров и 52/50 групп ДО, против
    11491 кадра и 84/79 групп ПОСЛЕ; порча служебных ячеек — ноль записей.

    ⛔ ТЕОРИЯ ОПРОВЕРГНУТА 24.08, ПРАВКА ВЫКЛЮЧЕНА ПО УМОЛЧАНИЮ.
    Обе таблицы отрисовки ($CF8A и $CFBC) содержат по ШЕСТЬ записей = 48 байт:
    от $FF0098 это доходит лишь до $FF00C8, а буфер 128 байт. Выхода за край
    НЕТ, и объяснение «убегает и топчет режим» неверно. Почему числа всё-таки
    менялись — не установлено; на одном сиде из трёх, а на двух других ноль.
    ⚠️ И главное: сдвиг буферов ЛОМАЕТ КАРТИНКУ — падающие фигуры перестают
    рисоваться (слово владельца: «не вижу даже как падают фигуры»).
    Оставлено выключенным как запись неудачной гипотезы, чтобы не искали заново.
    """
    for i, baza in enumerate(ПРОСТОР):
        slot = 0xFF1000 + 0x400 * i
        md.wl(slot + 0x0E, baza)
        md.wl(slot + 0x16, baza + 0x400)
        md.wl(slot + 0x1C, baza + 0x800)
        md.wl(slot + 0x20, baza + 0xC00)


# ------------------------------------------------- одиночный режим (путь А)
#
# Своего режима «играть одному» в игре нет (docs\IGRA.md, раздел 2).
# Берём 1on1 и держим второго игрока безвредным: каждый кадр чистим его поле
# и обнуляем шкалу атаки. Он не заваливается и не шлёт мусор — раунд не
# кончается, и первый игрок укладывает фигуры, пока не завалится сам.
#
# ПЗУ остаётся байт в байт ванильным: правится только ОЗУ на ходу.

def enable_solo(md, victim=P2, hero=P1, freeze_level=True):
    """Одиночный режим поверх боя 1on1. ПЗУ не трогается — только ОЗУ на ходу.

    Рецепт собран опытом, каждая строка нужна (см. docs\IGRA.md, раздел 11):

    * поле соперника чистится каждый кадр — ему нечем ни завалиться, ни бить;
    * его шкала атаки гасится, чтобы не летел мусор;
    * ⚠️ +0x4C НЕЛЬЗЯ держать нулём: это не «высота завала», а счётчик снижения
      фигуры (идёт 4,8,12,16,20). Если обнулять каждый кадр, конечный автомат
      игры ломается и через пять ходов управление улетает в никуда. Поэтому
      трогаем только у самого порога;
    * игра ведёт СВОЙ учёт высоты, стиранием поля его не обманешь — поэтому
      порог всё равно однажды достигается, и метку выбывания приходится снимать;
    * уровень держим постоянным: иначе каждые 35 фигур игра ускоряет падение и
      подсовывает служебную фигуру-метку (7,8,9), которой бот не управляет.
    """
    if getattr(md, '_solo', False):
        return md
    original = md.step_frame
    span = TOTAL * ROW              # 19 рядов подряд = 304 байта

    def neutralize():
        fix_empty_slots(md)
        md.ww(victim + 0x5A, 0)     # шкала атаки
        md.ww(victim + 0x9E, 0)     # сила посланной атаки
        if md.rw(victim + 0x4C) >= 16:
            md.ww(victim + 0x4C, 4)
        # Игра числит соперника выбывшим и потому «добивает» последнего
        # выжившего ($00EE40): нашему игроку прилетает та же метка $1000 в
        # +0x5C, хотя стопка у него низкая. Метку снимаем обоим, а счёт групп
        # игроку возвращаем — иначе он теряется вместе с меткой.
        md.ww(victim + 0x88, 0)
        md.ww(hero + 0x88, 0)
        # ⚠️ Сравнивать РОВНО с $1000 нельзя: игрок метку переживает и играет
        # дальше, а счётчик групп растёт ОТ неё (наблюдение 24.08 на записи:
        # 4096 → 4097 → 4098). Опоздали на кадр — и ветка `else` запишет 4097
        # в теневой счёт как «честный», после чего метка не снимется уже
        # никогда. Поэтому порог, а не равенство; прибавку после метки
        # сохраняем, чтобы собранные группы не пропали.
        if md.rw(victim + 0x5C) >= 0x1000:
            md.ww(victim + 0x5C, 0)
        g = md.rw(hero + 0x5C)
        if g >= 0x1000:
            md.ww(hero + 0x5C, getattr(md, '_groups', 0) + (g - 0x1000))
        else:
            md._groups = g
        if freeze_level:
            md.ww(hero + 0x8C, 0)
            md.ww(victim + 0x8C, 0)
            if md.rw(victim + 0x70) >= 30:
                md.ww(victim + 0x70, 0)
        base = field_base(md, victim)
        if base:
            top = base - HIDDEN * ROW
            blk = bytearray(md.uc.mem_read(top, span))
            dirty = False
            for r in range(TOTAL):
                o = r * ROW
                for c in range(COLS):
                    i = o + c * 2
                    if blk[i] or blk[i + 1]:
                        blk[i] = blk[i + 1] = 0
                        dirty = True
            if dirty:               # чаще всего поле уже чистое — тогда не пишем
                md.uc.mem_write(top, bytes(blk))

    def step():
        original()
        neutralize()

    md.step_frame = step
    md._solo = True
    md._freeze_level = freeze_level
    neutralize()
    return md


# ---------------------------------------------------------------- действия

class Hands:
    """Ставит текущую фигуру в заданную колонку с заданным поворотом.

    Кнопку нельзя держать: игра засчитывает удержание за одно нажатие,
    поэтому каждый ход — такт «нажал / отпустил».
    """

    def __init__(self, md, port=0, p=P1):
        self.md, self.port, self.p = md, port, p

    def tap(self, btn, hold=2, gap=2):
        self.md.press(self.port, btn)
        for _ in range(hold):
            self.md.step_frame()
        self.md.release(self.port)
        for _ in range(gap):
            self.md.step_frame()

    def _same_piece(self, n0):
        return (placed(self.md, self.p) == n0
                and in_battle(self.md)
                and not self.md.stopped)

    def rotate_to(self, want, budget=48):
        """Жмёт поворот, пока живые цвета не станут нужными.

        Считать нажатия нельзя: сразу после падения предыдущей фигуры новая
        ещё не слушается кнопок, и такие нажатия пропадают впустую.
        """
        md, p = self.md, self.p
        n0 = placed(md, p)
        while budget > 0:
            if live_piece(md, p) == want:
                return True
            self.tap('b'); budget -= 4
            if not self._same_piece(n0):
                return False
        return live_piece(md, p) == want

    def move_to(self, col, budget=64):
        md, p = self.md, self.p
        n0 = placed(md, p)
        while budget > 0 and piece_col(md, p) != col:
            self.tap('right' if piece_col(md, p) < col else 'left'); budget -= 4
            if not self._same_piece(n0):
                return False
        return piece_col(md, p) == col

    def slam(self, limit=200):
        """Ускоренное падение до укладки."""
        md, p = self.md, self.p
        n0 = placed(md, p)
        for _ in range(limit):
            md.press(self.port, 'down')
            md.step_frame()
            if not self._same_piece(n0):
                break
        md.release(self.port)
        for _ in range(3):
            md.step_frame()

    def place(self, col, want):
        """Полный ход: довернуть до нужных цветов, довести до колонки, уронить.

        Возвращает цвета, которые реально ушли в поле (их и надо отдавать клону).
        """
        rot_ok = self.rotate_to(want)
        col_ok = self.move_to(col)
        used = live_piece(self.md, self.p)
        self.slam()
        if getattr(self.md, '_freeze_level', False):
            self.md.ww(self.p + 0x70, 0)   # счётчик фигур не должен дойти до 35
        return used, rot_ok, col_ok
