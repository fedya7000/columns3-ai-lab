# ТУРНИРНЫЙ РЕЖИМ для боя 1 на 1 (Columns III, USA) — правила турниров по тетрису.
#
# ЧТО ДЕЛАЕТ
#   1. ОЧКИ. За каждый сбор начисляется  группы * множитель(длина цепочки):
#      цепочка 0 -> x1, 1 -> x2, 2 -> x4, 3 -> x8, 4 -> x16, 5 и длиннее -> x32.
#      Очки живут в СВОЁМ поле +0xE4 структуры игрока и показываются в белом
#      окошке вместо прежнего счётчика групп.
#   2. ПРАВИЛО ТУРНИРА. Кто завалился первым — ставит планку. Второго больше
#      НЕ добивают автоматически: он играет один, пока не ПЕРЕБЬЁТ её счёт.
#      Перебил — раунд его. Завалился, не догнав, — раунд у первого.
#   3. ПОБЕДА РАУНДА даётся по ОЧКАМ, а не по тому, кто продержался дольше.
#      При равных очках выигрывает тот, кто выбыл РАНЬШЕ (как в тетрисе:
#      догоняющий обязан ПЕРЕБИТЬ, а не сравнять).
#
# ПОЧЕМУ ОЧКИ ЛЕЖАТ ОТДЕЛЬНО, А НЕ В ГОТОВОМ СЧЁТЧИКЕ
#   Поле +0x5C (белое число оригинала) управляет СИЛОЙ АТАКИ по сопернику:
#   на $00DF26 игра берёт его прирост за каскад и кладёт в +0x9E. Умножить его
#   значило бы сломать баланс игры, а не добавить счёт. Поле +0x8C игра сама
#   обнуляет по ходу раунда. Поэтому взято +0xE4: замером показано, что во
#   время игры туда не пишет никто, а между раундами оно обнуляется само.
#
# ГДЕ НЕ ТРОГАЕТ
#   Всё включается только при $FF0418 == 1 (бой 1on1). Сюжетный режим
#   ($FF0418 == 0) и режимы на 3-6 игроков работают ровно как раньше.
import os, sys
from struct import pack
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'tools'))
from asm import Asm

ROM = os.path.join(os.path.dirname(__file__), '..', 'rom', 'Columns III (USA).gen')
_rom = open(ROM, 'rb').read()

# --- новый код в свободном хвосте ROM ($7A386..$7FFFF — чистые $FF) ---
SCORE = 0x07A400          # начисление очков
RULE = 0x07A480           # правило «перебей счёт выбывшего»
WINNER = 0x07A540         # надпись WIN!/LOSE — по очкам
TALLY = 0x07A620          # раздача побед/поражений — по очкам
DISP = 0x07A6A0           # что показывать в белом окошке

A6 = 6                    # структура игрока в игре всегда в a6
P1A, P2A = 0x00FF1000, 0x00FF1400
PTS = 0xE4                # ← наше поле очков
MODE_1ON1 = 0x00FF0418

# ------------------------------------------------------------------ очки
s = Asm(SCORE)
s.movem_save(0xD080)                   # сохранить d0/d1/d3/a0
s.add_w_dn_d16a6(2, 0x5C)              # ванильное: сила атаки и счётчик групп
s.add_w_dn_d16a6(2, 0x8C)              # ванильное: копия
s.cmpi_w_abs(1, MODE_1ON1)
s.bcc('ne', 'out')                     # не 1on1 — очки не начисляем
s.move_w_d16an_dn(A6, 0x6C, 3)         # d3 = длина цепочки
# в d1 к этому месту уже подмешан бонус цепочки (цепочка*4, добавлен на $DF7C),
# вычитаем его обратно — нужны ЧИСТЫЕ камни
s.move_w_dn_dn(3, 0)
s.asl_w_imm_dn(2, 0)                   # d0 = цепочка * 4
s.sub_w_dn_dn(0, 1)                    # d1 = собранные камни без бонуса
s.cmpi_w_dn(5, 3)
s.bcc('le', 'ok')
s.moveq(5, 3)                          # длиннее пяти считаем как пять
s.label('ok')
s.lea_label('mult', 0)
s.move_b_idx_dn(0, 3, 0)               # d0 = множитель за цепочку
s.andi_w_dn(0x00FF, 0)
s.move_w_dn_dn(1, 3)                   # d3 = число собранных КАМНЕЙ
s.mulu_dn_dn(0, 3)                     # d3 = камни * множитель
s.add_w_dn_d16a6(3, PTS)               # ← ОЧКИ
s.cmpi_w_d16a6(0x270F, PTS)            # потолок 9999 — под четыре цифры
s.bcc('le', 'out')
s.move_w_imm_d16a6(0x270F, PTS)
s.label('out')
s.movem_restore(0x010B)
s.rts()
s.label('mult')
s.db(1, 2, 4, 8, 16, 32)               # ← КРУТИЛКА: множители за длину цепочки
SCORE_CODE = s.assemble()

# ------------------------------------------- правило «перебей счёт выбывшего»
r = Asm(RULE)
r.cmpi_w_abs(1, MODE_1ON1)
r.bcc('ne', 'vanilla')
r.lea_abs(P1A, 0)
r.lea_abs(P2A, 1)
r.cmpi_w_d16an(0x1C, 0, 0x4C)          # игрок 1 выбыл?
r.bcc('ge', 'p1dead')
r.cmpi_w_d16an(0x1C, 1, 0x4C)          # игрок 2 выбыл?
r.bcc('ge', 'p2dead')
r.rts()                                # оба живы — не вмешиваемся

r.label('p1dead')                      # выбыл первый, играет второй
r.cmpi_w_d16an(0x1C, 1, 0x4C)
r.bcc('ge', 'done')                    # оба выбыли — раунд кончится сам
r.move_w_d16an_dn(1, PTS, 0)           # d0 = очки выжившего
r.cmp_w_d16an_dn(0, PTS, 0)            # против очков выбывшего
r.bcc('ls', 'done')                    # не перебил — играет дальше
r.movea_l_an_a6(1)
r.jmp_abs(0x0000EE40)                  # перебил — завершить раунд

r.label('p2dead')                      # выбыл второй, играет первый
r.move_w_d16an_dn(0, PTS, 0)
r.cmp_w_d16an_dn(1, PTS, 0)
r.bcc('ls', 'done')
r.movea_l_an_a6(0)
r.jmp_abs(0x0000EE40)

r.label('done')
r.rts()
r.label('vanilla')
r.jmp_abs(0x0000EDAA)                  # прочие режимы — как было
RULE_CODE = r.assemble()

# ------------------------------------------------ надпись WIN!/LOSE по очкам
w = Asm(WINNER)
w.cmpi_w_abs(1, MODE_1ON1)
w.bcc('ne', 'vanilla')
w.lea_abs(P1A, 0)
w.lea_abs(P2A, 1)
w.move_w_d16an_dn(0, PTS, 1)           # d1 = очки игрока 1
w.cmp_w_d16an_dn(1, PTS, 1)            # против очков игрока 2
w.bcc('hi', 'p1win')
w.bcc('lo', 'p2win')
# очки равны — выигрывает тот, кто выбыл РАНЬШЕ (у него +0x88 меньше)
w.move_w_d16an_dn(0, 0x88, 1)
w.cmp_w_d16an_dn(1, 0x88, 1)
w.bcc('lo', 'p1win')
w.bcc('hi', 'p2win')
w.move_w_abs_dn(0x00FFEF90, 2)         # совсем поровну — монетка, как в оригинале
w.andi_w_dn(1, 2)
w.bcc('eq', 'p1win')
w.label('p2win')
w.move_b_imm_d16an(1, 1, 0xE1)
w.rts()
w.label('p1win')
w.move_b_imm_d16an(1, 0, 0xE1)
w.rts()
w.label('vanilla')
w.raw(_rom[0x6DCE:0x6E1A].hex())       # копия оригинального выбора для прочих режимов
WINNER_CODE = w.assemble()

# ------------------------------------------ раздача побед/поражений по очкам
t = Asm(TALLY)
t.cmpi_w_abs(1, MODE_1ON1)
t.bcc('ne', 'van')
t.lea_abs(P1A, 0)
t.lea_abs(P2A, 1)
t.move_w_d16an_dn(1, PTS, 0)           # d0 = очки игрока 2
t.cmp_w_d16an_dn(0, PTS, 0)            # против очков игрока 1
t.bcc('eq', 'tie')
t.bcc('gt', 'p2')                      # у игрока 2 больше — победил он
t.jmp_abs(0x000043A4)                  # иначе победил игрок 1
t.label('tie')                         # очки равны — победил ВЫБЫВШИЙ РАНЬШЕ
t.move_w_abs_dn(0x00FF1488, 0)         # порядок выбывания игрока 2
t.cmp_w_abs_dn(0x00FF1088, 0)          # против игрока 1
t.bcc('eq', 'draw')
t.bcc('gt', 'p1')                      # игрок 2 выбыл позже — победил игрок 1
t.jmp_abs(0x000043B2)                  # игрок 2 выбыл раньше — победил он
t.label('p1')
t.jmp_abs(0x000043A4)
t.label('draw')
t.jmp_abs(0x000043C0)
t.label('p2')
t.jmp_abs(0x000043B2)
t.label('van')                         # прочие режимы — как было: по порядку выбывания
t.move_w_abs_dn(0x00FF1488, 0)
t.cmp_w_abs_dn(0x00FF1088, 0)
t.bcc('eq', 'draw2')
t.bcc('gt', 'p2b')
t.jmp_abs(0x000043A4)
t.label('draw2')
t.jmp_abs(0x000043C0)
t.label('p2b')
t.jmp_abs(0x000043B2)
TALLY_CODE = t.assemble()

# ------------------------------------- что показывать в белом окошке на экране
d = Asm(DISP)
d.moveq(0, 0)                          # так было в оригинале: moveq #0,d0
d.cmpi_w_abs(1, MODE_1ON1)
d.bcc('ne', 'van')
d.move_w_d16an_dn(A6, PTS, 0)          # 1on1 — показываем ОЧКИ
d.rts()
d.label('van')
d.move_w_d16an_dn(A6, 0x5C, 0)         # прочие режимы — как было
d.rts()
DISP_CODE = d.assemble()

