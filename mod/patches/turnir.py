# ================== ПОЧИНКА МУСОРНОЙ ПЕРЕСЫЛКИ ==================
#
# Болезнь: изредка (примерно раз в 8-10 тысяч кадров) игра отправляет в видеочип
# заявку на пересылку с мусорными параметрами — вместо регистров DMA туда летят
# байты машинного кода. На приставке это выброс мусора в видеопамять, у нас —
# чтение за границей памяти.
#
# Причина разобрана до строки. Анимации петухов-маскотов заданы скриптами, где
# байт $FF — команда «начать заново». Обработчик этой команды ($010754)
# перечитывает ПЕРВЫЙ байт скрипта и отдаёт его как номер кадра, НЕ ПРОВЕРЯЯ,
# не команда ли это снова. Если указатель на скрипт съехал (в пойманном случае
# он указывал на область графики, где первый байт тоже $FF), наружу уходит
# номер кадра 255 — и чтение таблицы на $10944 уезжает на 3.5 КБ за её конец.
#
# Лечение: если перечитанный байт снова оказался командой (старший бит стоит),
# берём кадр 0 — заведомо годный. Это НЕ мой баг: он воспроизводится и на
# чистом оригинале (tools/soak.py, зерно 11).
ANIMFIX = 0x07A980
ANIMFIX_CODE = bytes.fromhex(
    '12280001'      # move.b $1(a0), d1   — как было: взять первый байт скрипта
    '422e00b9'      # clr.b  $b9(a6)      — как было: номер кадра на ноль
    '4a01'          # tst.b  d1
    '6a02'          # bpl    дальше       — байт меньше $80, это настоящий кадр
    '7200'          # moveq  #0, d1       — это снова команда: берём кадр 0
    '4e75'          # rts
)

# ⛔ ЗАПЛАТКА ОТКАЧЕНА И В СБОРКУ НЕ ИДЁТ.
# Проверка показала: она лечит симптом, а не причину. С ней игра перестаёт
# слать мусорную заявку, но через полторы тысячи кадров падает РАНЬШЕ и в другом
# месте ($010706) — там, где по УЖЕ испорченному указателю +0xB4 читается скрипт.
# Значит корень в том, кто портит сам указатель, а он пока не найден:
# таблица скриптов ($10812, 33 записи) чистая, номер состояния +0xB8 за неё не
# выходит (замер tools/anim_state.py: максимум 31 из 33).
# Оставляю как было и доискиваюсь отдельно.

# ================== АТАКА ОТВЯЗАНА ОТ КНОПОК ==================
#
# Зачем: играют вдвоём без «подлян», а атака висит на двух кнопках из трёх
# вплотную к повороту фигуры, и её задевают случайно. В меню CONFIGURATION
# схема ПЕРЕНАЗНАЧАЕТСЯ (курсор встаёт на строку ATTACK, кнопка A листает три
# варианта: поворот на B / на A / на C), но две кнопки всегда остаются атакой —
# отвязать полностью можно только правкой.
#
# Как найдено: схема лежит в $FF046A, раздаётся на $00947A по таблице $94AA
# (по 4 байта на вариант: бит поворота, бит атаки 1, бит атаки 2), а сами биты
# проверяются на $00E9CC и $00E9DC.
#
# Правка: блок проверки кнопок ($00E9C8..$00E9F1, 42 байта) заменён прыжком на
# свою версию, которая в бою 1on1 кнопки атаки просто не смотрит. В остальных
# режимах повторяет исходное поведение байт в байт.
NOATK = 0x07A9C0
_n = Asm(NOATK)
_n.cmpi_w_abs(1, MODE_1ON1)
_n.bcc('ne', 'vanilla')
# бой 1 на 1: кнопки атаки не опрашиваем вовсе
_n.raw('4a6e0080')                     # tst.w $80(a6) — уже заявленная атака
_n.bcc('ne', 'exec')
_n.rts()
_n.label('vanilla')
_n.raw('286e0024')                     # movea.l $24(a6), a4
_n.raw('102e00ae')                     # move.b  $ae(a6), d0
_n.raw('012e0041')                     # btst.l  d0, $41(a6)
_n.bcc('ne', 'arm')
_n.raw('286e0028')                     # movea.l $28(a6), a4
_n.raw('102e00af')                     # move.b  $af(a6), d0
_n.raw('012e0041')                     # btst.l  d0, $41(a6)
_n.bcc('ne', 'arm')
_n.raw('4a6e0080')                     # tst.w $80(a6)
_n.bcc('ne', 'exec')
_n.rts()
_n.label('arm')
_n.jmp_abs(0x0000E9F2)                 # родной блок «заявить атаку»
_n.label('exec')
_n.jmp_abs(0x0000E9FC)                 # родной блок «выполнить атаку»
NOATK_CODE = _n.assemble()

# ================== ЗАЩИТА ПОСТРОИТЕЛЯ СПИСКА СПРАЙТОВ ==================
#
# Болезнь (пре-существующая, ловится долгим прогоном): построитель списка
# спрайтов `sub_00CE52` берёт указатель из +0x0E структуры игрока и пишет по
# нему 48 байт. Если он запускается для ПУСТОГО слота игрока (в бою вдвоём
# заняты только два первых), указатель там мусорный, и запись идёт куда попало —
# в пойманном случае затёрло число игроков ($FF0422 стало 26114), после чего
# игра полезла обрабатывать несуществующего третьего игрока и рухнула.
#
# Лечение — сторож, а не догадка: если указатель не лежит в области буфера
# спрайтов ($FF0000..$FF03FF), построитель просто не работает. Правильные
# указатели ($FF0080 у первого игрока, $FF0100 у второго) внутрь попадают,
# поэтому на исправную игру сторож не влияет никак.
LISTGUARD = 0x07AA40
_g = Asm(LISTGUARD)
_g.raw('206e000e')                     # movea.l $e(a6), a0     — как было
_g.raw('b1fc00FF0000')                 # cmpa.l #$00FF0000, a0
_g.bcc('lo', 'bad')                    # ниже памяти — мусор
# Граница именно $FF0380, а не $FF0400: построитель пишет НЕ по самому
# указателю, а на 0x18 дальше и ещё 48 байт вперёд. С границей $FF0400
# мусорное значение чуть ниже неё всё равно доставало до числа игроков
# ($FF0422) и затирало его — поймано замером на зерне 29.
_g.raw('b1fc00FF0380')                 # cmpa.l #$00FF0380, a0
_g.bcc('hs', 'bad')                    # выше буфера спрайтов — мусор
_g.raw('42680060')                     # clr.w $60(a0)          — как было
_g.raw('42680068')                     # clr.w $68(a0)          — как было
_g.raw('42680070')                     # clr.w $70(a0)          — как было
_g.jmp_abs(0x0000CE62)                 # дальше родной код
_g.label('bad')
_g.rts()                               # мусорный указатель — память не трогаем
LISTGUARD_CODE = _g.assemble()

# ================== ПОЧИНКА МУСОРНОЙ ПЕРЕСЫЛКИ (корень) ==================
#
# Болезнь: изредка игра отправляет в видеочип заявку на пересылку с мусорными
# параметрами — вместо регистров DMA туда летят байты машинного кода. На
# приставке это выброс мусора в видеопамять, у нас — чтение за границей памяти
# ($0039EA). Есть и в чистом оригинале: 5 сбоев на 10 зёрен долгого прогона.
#
# Корень пойман замером (tools/catch_b4.py). Анимации петухов-маскотов выбираются
# по номеру состояния +0xB8; на $010698 он умножается на 4 и по нему читается
# таблица скриптов $10812, в которой РОВНО 33 записи. В пойманном случае номер
# оказался 176 — чтение уехало на 704 байта за конец таблицы, в область графики,
# и в указатель скрипта +0xB4 легло $0002D5FE. Дальше из «скрипта» вылезал
# номер кадра 255, а по нему — мусорная заявка DMA.
#
# ⚠️ Первая попытка лечила СИМПТОМ (обработчик команды $FF в скрипте) и делала
# хуже: сбой переезжал раньше и в другое место. Лечим причину: номер состояния,
# не попадающий в таблицу, заменяется на 0 (спокойная поза).
ANIMCLAMP = 0x07AAC0
_a = Asm(ANIMCLAMP)
_a.raw('0c000021')                     # cmpi.b #33, d0   — размер таблицы скриптов
_a.bcc('lo', 'ok')
_a.moveq(0, 0)                         # вне таблицы — состояние 0
_a.label('ok')
_a.raw('1d4000b8')                     # move.b d0, $b8(a6)  — как было
_a.jmp_abs(0x0001068C)                 # дальше родной код
ANIMCLAMP_CODE = _a.assemble()

