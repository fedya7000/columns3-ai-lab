# СВОЯ МЕЛОДИЯ для звукового драйвера Columns III.
#
# Формат вскрыт разбором кода Z80 (см. docs/SOSTOYANIE.md):
#   $80        — пауза
#   $81..$DF   — нота, номер полутона = байт - $81
#                (октава = полутон/12, ступень = полутон%12, ступень 0 — «до»)
#   < $80      — длительность предыдущей ноты
#   $F6 lo hi  — переход по адресу (им и зацикливаем, чтобы играло без конца)
#
# Мелодия кладётся в СВОБОДНЫЙ хвост звукового блока Z80 и заканчивается
# переходом на саму себя — поэтому звучит постоянно, а не обрывается.

# ---- ноты: имя -> ступень в октаве ----
STEP = {'do': 0, 'do#': 1, 're': 2, 're#': 3, 'mi': 4, 'fa': 5, 'fa#': 6,
        'sol': 7, 'sol#': 8, 'la': 9, 'la#': 10, 'si': 11}


def n(name, octave, dur):
    """Нота: имя, октава (0..7), длительность."""
    return ('n', STEP[name] + octave * 12, dur)


def p(dur):
    """Пауза заданной длительности."""
    return ('p', 0, dur)


# ============================================================================
# «Лунная легенда» (Moonlight Densetsu) — заглавная тема «Сейлор Мун».
#
# ⚠️ ЗАПИСАНО ПО ПАМЯТИ. Ноты — моя расшифровка на слух-по-памяти, и она вполне
# может врать. Проверяет ВЛАДЕЛЕЦ: слушает и говорит, где не то. Править легко —
# это обычный список ниже, одна строка на ноту.
#
# Длительность: 12 — четверть, 6 — восьмая, 24 — половинная.
#
# ТЕМП. Длительности заданы в тиках драйвера, а сколько это в секундах — зависит
# от темпа мелодии, на слух я его не проверял. Если играет слишком быстро или
# слишком медленно, крутить ОДНУ ручку ниже: больше единицы — медленнее.
# ============================================================================
TEMPO = 1.0
Q, E, H, W = 12, 6, 24, 48

# ⚠️ РЕГИСТР. Октавы обязаны совпадать с ТЕМ каналом, который мы заменяем.
# У боевой темы $8D мелодию ведёт канал Z80 $A162, и он играет в октавах 4-5
# (си4, до5, ля4) — поэтому и мелодия здесь в 4-5. Проверять командой:
#   python tools\seq_decode.py --bgm 8D
MOONLIGHT = [
    # «Го-мэн нэ су-на-о дзя на-ку-тэ»
    n('sol', 4, E), n('la', 4, E), n('si', 4, Q), n('do', 5, Q),
    n('si', 4, E), n('la', 4, E), n('sol', 4, H),
    p(E),
    n('mi', 4, E), n('sol', 4, E), n('la', 4, Q), n('si', 4, Q),
    n('la', 4, E), n('sol', 4, E), n('mi', 4, H),
    p(E),
    # «ю-мэ но на-ка на-ра су-на-о ни и-э-ру»
    n('do', 5, E), n('re', 5, E), n('mi', 5, Q), n('re', 5, Q),
    n('do', 5, E), n('si', 4, E), n('la', 4, H),
    p(E),
    n('sol', 4, E), n('la', 4, E), n('si', 4, Q), n('la', 4, Q),
    n('sol', 4, E), n('mi', 4, E), n('re', 4, H),
    p(Q),
    # припев: «Му-ун-ра-й-то дэн-сэ-цу»
    n('do', 5, Q), n('si', 4, E), n('la', 4, E), n('sol', 4, Q), n('la', 4, Q),
    n('si', 4, H),
    p(E),
    n('do', 5, Q), n('re', 5, E), n('mi', 5, E), n('re', 5, Q), n('do', 5, Q),
    n('si', 4, H),
    p(Q),
]


def encode(notes, loop_addr, setup=b''):
    """Собирает поток байт: настройка канала, ноты, переход на начало."""
    out = bytearray(setup)
    for kind, semi, dur in notes:
        if kind == 'p':
            out.append(0x80)
        else:
            if not (0 <= semi <= 0x5E):
                raise ValueError(f'полутон {semi} вне диапазона 0..94')
            out.append(0x81 + semi)
        d = int(round(dur * TEMPO))
        if not (1 <= d < 0x80):
            raise ValueError(
                f'длительность {dur} при темпе {TEMPO} даёт {d} — надо 1..127')
        out.append(d)
    out += bytes([0xF6, loop_addr & 0xFF, (loop_addr >> 8) & 0xFF])
    return bytes(out)


if __name__ == '__main__':
    data = encode(MOONLIGHT, 0x1B58)
    print(f"нот и пауз: {len(MOONLIGHT)}")
    print(f"байт: {len(data)}")
    print(data.hex(' '))
